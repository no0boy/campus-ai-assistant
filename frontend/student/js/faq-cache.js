// ==================== localStorage 缓存管理 ====================

const CACHE_KEY = 'qa_cache'
const CACHE_MAX = 100

/**
 * 获取缓存（先查 localStorage 精确匹配 → 再查 FAQ 关键词匹配）
 * @param {string} question
 * @returns {object|null} {answer, sources, search_method, fromCache: true}
 */
function getCachedAnswer(question) {
  const q = question.trim()

  // ① localStorage 精确匹配
  try {
    const cache = JSON.parse(localStorage.getItem(CACHE_KEY) || '{}')
    if (cache[q]) {
      cache[q].time = Date.now()  // 更新访问时间
      // 异步写回，不阻塞返回
      setTimeout(() => {
        try { localStorage.setItem(CACHE_KEY, JSON.stringify(cache)) } catch(e) {}
      }, 0)
      return { ...cache[q].data, fromCache: true }
    }
  } catch(e) {}

  // ② FAQ 关键词模糊匹配
  const qLower = q.toLowerCase()
  for (const [key, value] of Object.entries(FAQ_CACHE)) {
    // 问题包含 FAQ 关键词的全部
    const keywords = key.replace(/[？?！!]/g, '').split('')
    if (keywords.length >= 3 && keywords.every(k => q.includes(k))) {
      return { ...value, fromCache: true, fromFAQ: true }
    }
  }

  return null
}

/**
 * 缓存答案到 localStorage
 * @param {string} question
 * @param {object} data - {answer, sources, search_method}
 */
function cacheAnswer(question, data) {
  try {
    const cache = JSON.parse(localStorage.getItem(CACHE_KEY) || '{}')
    cache[question.trim()] = { data, time: Date.now() }

    // LRU 淘汰：超过最大条数时删除最旧的
    const keys = Object.keys(cache)
    if (keys.length > CACHE_MAX) {
      const oldest = keys.sort((a, b) => cache[a].time - cache[b].time)[0]
      delete cache[oldest]
    }

    localStorage.setItem(CACHE_KEY, JSON.stringify(cache))
  } catch(e) {
    // localStorage 满了就清空重来
    try { localStorage.removeItem(CACHE_KEY) } catch(e2) {}
  }
}
